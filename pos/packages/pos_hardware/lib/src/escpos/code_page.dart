import 'dart:typed_data';

/// Printerning belgilar jadvali (code page): qaysi Unicode belgi qaysi baytga tushadi va jadval `ESC t n` bilan qanday
/// tanlanadi. ASCII (0x20–0x7E) hamma jadvalda bir xil.
///
/// [table] raqami printer modeliga bog'liq (Epson: PC866 = 17, WPC1251 = 46; ko'p Xprinter/Rongta ham shunday, lekin
/// ba'zilarida boshqacha): printer sozlamasida o'zgartiriladi, sinov sahifasi bilan tekshiriladi.
final class EscPosCodePage {
  const EscPosCodePage._(this.name, this.table, this._upper);

  /// Faqat ASCII (PC437 jadvali 0). Boshqa har qanday belgi — transliteratsiya yoki rasm.
  static const EscPosCodePage ascii = EscPosCodePage._(
    'ascii',
    0,
    <int, int>{},
  );

  /// DOS kirill (PC866): rus kirili, Ў ў, №. Qoraqalpoq/o'zbek Қ Ғ Ҳ yo'q.
  static const EscPosCodePage cp866 = EscPosCodePage._('cp866', 17, _cp866);

  /// Windows kirill (WPC1251): rus kirili, Ў ў, №, « », – —.
  static const EscPosCodePage cp1251 = EscPosCodePage._('cp1251', 46, _cp1251);

  static const List<EscPosCodePage> values = <EscPosCodePage>[
    ascii,
    cp866,
    cp1251,
  ];

  /// Sozlamadagi nomdan; noma'lum — [cp866] (bozordagi printerlarning ko'pchiligida bor).
  static EscPosCodePage byName(String? name) {
    for (final EscPosCodePage p in values) {
      if (p.name == name) return p;
    }
    return cp866;
  }

  final String name;

  /// `ESC t n` dagi `n`.
  final int table;

  /// Unicode → bayt (0x80–0xFF).
  final Map<int, int> _upper;

  /// Boshqa jadval raqami bilan (printer modeli boshqa raqam ishlatsa).
  EscPosCodePage withTable(int table) => EscPosCodePage._(name, table, _upper);

  /// Belgi shu jadvalda to'g'ridan-to'g'ri bormi (transliteratsiyasiz).
  bool canEncodeRune(int rune) =>
      (rune >= 0x20 && rune < 0x7F) || rune == 0x0A || _upper.containsKey(rune);

  /// Matndagi hamma belgi to'g'ridan-to'g'ri chiqadimi. `false` bo'lsa (masalan, "oʻ", "gʻ", "Қ") — matn rejimida
  /// almashtiriladi, "auto" rejimda esa hujjat rasm sifatida chop etiladi.
  bool canEncode(String text) => text.runes.every(canEncodeRune);

  /// Matnni baytlarga aylantiradi. Jadvalda yo'q belgi [transliterate] bilan yaqiniga almashtiriladi ("oʻ" → "o'",
  /// "Қ" → "К"); u ham bo'lmasa — `?`.
  Uint8List encode(String text) {
    final BytesBuilder out = BytesBuilder(copy: false);
    for (final int rune in text.runes) {
      final int? b = _byteOf(rune);
      if (b != null) {
        out.addByte(b);
        continue;
      }
      final String? alt = transliterate(rune);
      if (alt != null) {
        for (final int r in alt.runes) {
          out.addByte(_byteOf(r) ?? 0x3F);
        }
      } else {
        out.addByte(0x3F); // ?
      }
    }
    return out.takeBytes();
  }

  /// Baytlarni qayta matnga (emulyator va testlar uchun).
  String decode(List<int> bytes) {
    final Map<int, int> reverse = <int, int>{
      for (final MapEntry<int, int> e in _upper.entries) e.value: e.key,
    };
    return String.fromCharCodes(
      bytes.map((int b) => b < 0x80 ? b : (reverse[b] ?? 0xFFFD)),
    );
  }

  int? _byteOf(int rune) {
    if (rune < 0x80) return rune;
    return _upper[rune];
  }

  @override
  String toString() => 'EscPosCodePage($name, table $table)';
}

/// Printer jadvalida yo'q belgining yaqin almashtirishi; bilmasa `null`.
