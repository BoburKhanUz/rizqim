<?php
// php preload-list.php <raw classes file> [out]  -- builds backend/docker/preload-classes.txt (the OPcache preload list)
// from the classes real requests declared. Collect them with the profiler first, e.g.:
//   PROF=cpu PROF_CLASSES=$SCALE_WORK/logs/classes.txt SERVER=fpm ./server.sh start
//   node load.mjs ... --cfg '{"probe":{"reps":2}}'      (and any other scenario whose requests should be covered)
//   php php/prof/preload-list.php $SCALE_WORK/logs/classes.txt
// Dev-only packages (absent from the image), anonymous classes, Composer's own generated classes and a trait whose
// anonymous class can not be preloaded, with the two rules that use it (a warning at every php-fpm start), are left out.
$in = $argv[1] ?? exit("usage: php preload-list.php <classes.txt> [out]\n");
$out = $argv[2] ?? dirname(__DIR__, 4).'/backend/docker/preload-classes.txt';
$skip = '/^(PHPUnit|Faker|Mockery|NunoMaduro|SebastianBergmann|Termwind|Whoops|Laravel\\\\(Pail|Sail|Pint)|ProfApp|ComposerAutoloaderInit|Composer\\\\Autoload\\\\ComposerStaticInit|Illuminate\\\\(Foundation\\\\)?Testing|Illuminate\\\\Translation\\\\CreatesPotentiallyTranslatedStrings$|Illuminate\\\\Validation\\\\(Closure|Invokable)ValidationRule$)/';
$names = [];
foreach (file($in, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $n) {
    $n = trim($n);
    if ($n === '' || str_contains($n, '@anonymous') || str_contains($n, "\0") || preg_match($skip, $n)) continue;
    $names[$n] = true;
}
$names = array_keys($names);
sort($names);
file_put_contents($out, "# OPcache preload list (docker/preload.php), generated by scripts/scale-test/php/prof/preload-list.php\n"
    ."# from the classes the scale-test probe's requests declared. Regenerate after big changes; a stale list only costs speed.\n"
    .implode("\n", $names)."\n");
echo count($names)." classes -> $out\n";
